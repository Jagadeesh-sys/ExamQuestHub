/**
 * Extract all questions from the RRB NTPC Graduate 2025 (CEN 06/2025) CBT-1
 * official answer-key PDF stored in public/assets/aistudio.
 *
 * The PDF is a single mixed section per shift, so subjects are classified from
 * the question text rather than from question-number ranges (unlike the older
 * Under-Graduate compilation). The correct option is the option rendered in the
 * official green fill colour (#40c64b).
 *
 * Output: public/data/rrbNtpcGraduate2025Full.json
 */
import fs from 'fs';
import { PDFParse } from 'pdf-parse';
import { OPS } from 'pdfjs-dist';
import { classifyGkTopic, classifyComputerTopic } from '../src/services/rrbMockService.js';

const PDF_PATH = 'public/assets/aistudio/RRB-NTPC-Graduate-2025-CBT1-EN-Official-Answer-Key.pdf';
const OUT_PATH = 'public/data/rrbNtpcGraduate2025Full.json';
const GREEN = '#40c64b';
const LETTERS = ['A', 'B', 'C', 'D'];

const JUNK_PATTERNS = [
  /Test Center Name[\s\S]*?selected by the candidate\.?/g,
  /Section\s*:\s*RRB NTPC GRADUATE CBT 1/g,
  /Blackbook/g,
  /Generated by\s*/g,
  /rank\.qmaths\.in/g,
  /Get the Toppers Choice/g,
  /BLACKBOOK VOCAB APP/g,
  /Instructions/g,
  /-?\s*Download Now/g
];

/* ------------------------------------------------------------------ */
/* Text + colour extraction                                            */
/* ------------------------------------------------------------------ */

/**
 * Per-character run buffer: each entry keeps the glyph and its fill colour.
 * The answer-key PDF positions every line with its own text matrix and emits no
 * space glyph at line breaks, so a space is inserted whenever the device Y
 * changes between text runs (otherwise wrapped words merge: "amounts"+"spent").
 */
async function pageChars(parser, pageNo) {
  const page = await parser.doc.getPage(pageNo);
  const ops = await page.getOperatorList();
  let fill = '#000000';
  let ctm = [1, 0, 0, 1, 0, 0];
  let tx = 0;
  let ty = 0;
  let lastDevY = null;
  let started = false;
  const out = [];
  for (let i = 0; i < ops.fnArray.length; i++) {
    const fn = ops.fnArray[i];
    const args = ops.argsArray[i];
    if (fn === OPS.setFillRGBColor) {
      fill = String(args[0]).toLowerCase();
    } else if (fn === OPS.transform) {
      ctm = args;
    } else if (fn === OPS.setTextMatrix) {
      tx = args[0][4];
      ty = args[0][5];
    } else if (fn === OPS.moveText) {
      tx += args[0];
      ty += args[1];
    } else if (fn === OPS.setLeadingMoveText) {
      ty += args[1];
    } else if (fn === OPS.showText || fn === OPS.showSpacedText) {
      const devY = ctm[1] * tx + ctm[3] * ty + ctm[5];
      if (started && lastDevY !== null && Math.abs(devY - lastDevY) > 0.5) {
        out.push({ ch: ' ', fill });
      }
      for (const x of args[0] || []) {
        const ch = typeof x === 'string' ? x : x.unicode || '';
        // White glyphs are qmaths watermarks / figure ids, not question content.
        if (ch && fill !== '#ffffff') out.push({ ch, fill });
      }
      lastDevY = devY;
      started = true;
    }
  }
  return out;
}

/** Remove repeated header / footer boilerplate while keeping colour alignment. */
function stripBoilerplate(chars) {
  let text = chars.map((c) => c.ch).join('');
  for (const re of JUNK_PATTERNS) {
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(text))) {
      chars.splice(m.index, m[0].length);
      text = chars.map((c) => c.ch).join('');
      re.lastIndex = 0;
    }
  }
  return chars;
}

/* ------------------------------------------------------------------ */
/* Question parsing                                                    */
/* ------------------------------------------------------------------ */

/** Repair merged markers such as "Q.1320%" (Q.13 followed by question "20% ..."). */
function findMarkers(text) {
  const re = /Q\.(\d+)/g;
  const markers = [];
  let expected = 1;
  let m;
  while ((m = re.exec(text))) {
    let num = parseInt(m[1], 10);
    let end = re.lastIndex;
    if (num !== expected && m[1].startsWith(String(expected))) {
      num = expected;
      end = m.index + 2 + String(expected).length;
      re.lastIndex = end;
    }
    markers.push({ num, start: m.index, end });
    expected = num + 1;
  }
  return markers;
}

function cleanText(value) {
  return String(value || '')
    .replace(/\s+/g, ' ')
    .replace(/\s+([,.;:?])/g, '$1')
    .trim();
}

const LIGATURES = { '\uFB00': 'ff', '\uFB01': 'fi', '\uFB02': 'fl', '\uFB03': 'ffi', '\uFB04': 'ffl', '\uFB05': 'st', '\uFB06': 'st' };

/** Normalise ligature glyphs: single Unicode ligatures plus spaced-out runs. */
function fixLigatures(str) {
  return String(str || '')
    .replace(/[\uFB00-\uFB06]/g, (c) => LIGATURES[c] || c)
    .replace(/(\w)\s+(ffi|ffl|ff|fi|fl)\s+(\w)/g, '$1$2$3')
    .replace(/\b(ffi|ffl|ff|fi|fl)\s+(\w)/g, '$1$2')
    .replace(/(\w)\s+(ffi|ffl|ff|fi|fl)\b/g, '$1$2')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Parse one question block (chars between two Q markers). */
function parseQuestion(blockChars, fallbackLetter) {
  const text = blockChars.map((c) => c.ch).join('');

  // Question text ends where the "Ans" label starts (immediately followed by an option).
  let ansMatch = text.match(/Ans(?=\s*[A-D]\.)/);
  if (!ansMatch) ansMatch = text.match(/\bAns\b/);

  let questionText = text;
  let ansEnd = text.length;
  if (ansMatch) {
    questionText = text.slice(0, ansMatch.index);
    ansEnd = ansMatch.index + ansMatch[0].length;
  }

  const options = [];
  const optColors = [];
  const optRe = /([A-D])\.\s*/g;
  optRe.lastIndex = ansEnd;
  let m;
  while (options.length < 4 && (m = optRe.exec(text))) {
    if (m[1] !== LETTERS[options.length]) continue;
    const startText = optRe.lastIndex;
    let endText = text.length;
    // Option value runs up to the next option marker (A-D followed by a dot).
    const tail = text.slice(startText);
    const next = tail.match(/[A-D]\.\s/);
    if (next) endText = startText + next.index;

    const letterIdxInBlock = m.index;
    const letterColor = blockChars[letterIdxInBlock]?.fill || '';
    const colorTally = {};
    for (let ci = letterIdxInBlock; ci < Math.min(endText, blockChars.length); ci++) {
      const fill = blockChars[ci].fill;
      colorTally[fill] = (colorTally[fill] || 0) + 1;
    }
    const dominant = Object.entries(colorTally).sort((a, b) => b[1] - a[1])[0]?.[0] || letterColor;

    options.push(fixLigatures(cleanText(text.slice(startText, endText))));
    optColors.push({ letter: m[1], letterColor, dominant });
  }

  let correctLetter = fallbackLetter;
  const greenOpt = optColors.find((o) => o.letterColor === GREEN || o.dominant === GREEN);
  if (greenOpt) correctLetter = greenOpt.letter;

  return {
    questionText: fixLigatures(cleanText(questionText)),
    options,
    correctLetter,
    hasGreen: Boolean(greenOpt)
  };
}

/* ------------------------------------------------------------------ */
/* Subject / topic classification (content based)                      */
/* ------------------------------------------------------------------ */

const COMPUTER_RE =
  /\b(computer|cpu|ram|rom|software|hardware|internet|website|browser|http|url|operating system|windows|linux|firewall|compiler|motherboard|database|network|e-?mail|keyboard|mouse|printer|byte|kilobyte|megabyte|gigabyte|terabyte|petabyte|processor|cyber|excel|ms word|powerpoint|wifi|bluetooth|ascii|application software|file name|folder|cache|modem|router|server|domain|antivirus|malware|shortcut key|fourth generation of computers)\b/;

const SCIENCE_RE =
  /\b(physics|chemistry|biology|atomic|atom|molecule|element|periodic table|chemical|acid|base|salt|metal|alloy|gas|oxygen|hydrogen|carbon|photosynthesis|plant|animal|cell|tissue|organ|enzyme|hormone|vitamin|protein|carbohydrate|blood|heart|brain|kidney|liver|dna|gene|chromosome|disease|bacteria|virus|fungus|vaccine|immunity|ecosystem|biodiversity|gravity|motion|velocity|force|energy|momentum|friction|inertia|lens|mirror|refraction|reflection|wavelength|frequency|sound|ultrasonic|heat|temperature|thermodynamic|conductor|insulator|semiconductor|electric|voltage|resistance|magnet|radiation|newton|joule|pascal|barometer|optics|isotope|hydrocarbon|solar|starch|starfish|echinoderms|vertebrate|solstice|equinox|latitude|longitude|tropic of|equator|planet|moon|comet|galaxy|universe|atmosphere|ozone|greenhouse|constellation|orbit|eclipse)\b/;

const REASONING_RE =
  /\b(coding|decoding|code language|coded as|blood relation|sits? around|circular table|linear arrangement|floors? of the same building|statement(s)? and conclusion|syllogism|analogy|odd one out|alphabetical order|letter-cluster|letter-number cluster|letter and symbol series|number and symbol series|direction|mirror image|water image|paper folding|venn diagram|seating arrangement|symbol series|which of the following letter|replace the question mark|select the set in which the numbers are related|is related to .* following|data su ffi cien|data sufficien|in-centre|lives? on .* floo?r)\b/;

const QUANT_RE =
  /\b(average|percentage|percent|profit|loss|discount|marked price|simple interest|compound interest|per annum|ratio|proportion|proportional|time and work|work alone|cistern|pipes?|boats?|stream|downstream|upstream|speed|train|area|perimeter|volume|mensuration|hexagon|triangle|quadrilateral|circle|cylinder|sphere|algebra|equation|quadratic|hcf|lcm|divisible|median|mode|mean|frequency|sum of|age|ages|number is|number-pairs|evaluate|find the value|simplif|successive|partnership|mixture)\b/i;

function classifySubject(qText, options) {
  const combined = `${qText} ${options.join(' ')}`.toLowerCase();

  if (COMPUTER_RE.test(combined)) {
    return { subject: 'General Knowledge', subjectId: 'general-knowledge', subtopic: 'Computer Science' };
  }
  if (REASONING_RE.test(combined)) {
    return { subject: 'Reasoning', subjectId: 'reasoning', subtopic: classifyReasoningTopic(combined) };
  }
  if (SCIENCE_RE.test(combined)) {
    return { subject: 'General Science', subjectId: 'general-science', subtopic: classifyScienceTopic(combined) };
  }
  if (QUANT_RE.test(combined)) {
    return { subject: 'Quantitative Aptitude', subjectId: 'quantitative-aptitude', subtopic: classifyQuantTopic(combined) };
  }
  return { subject: 'General Knowledge', subjectId: 'general-knowledge', subtopic: classifyGkTopic({ question: { en: qText }, options: { en: options } }) };
}

function classifyScienceTopic(text) {
  if (/\b(acid|base|salt|atom|molecule|element|periodic table|chemical|metal|alloy|ore|gas|oxygen|hydrogen|carbon|hydrocarbon|combustion|oxidation|fertilizer|compound|reaction|starch|polymer)\b/.test(text)) return 'Chemistry';
  if (/\b(cell|tissue|organ|enzyme|hormone|vitamin|protein|carbohydrate|blood|heart|brain|kidney|liver|dna|gene|chromosome|disease|bacteria|virus|fungus|vaccine|immunity|ecosystem|biodiversity|plant|animal|photosynthesis|respiration|digestion|nerve|muscle|bone|lung|echinoderm|starfish)\b/.test(text)) return 'Biology';
  return 'Physics';
}

function classifyReasoningTopic(text) {
  if (/\b(code language|coded as|coding-decoding)\b/.test(text)) return 'Coding-Decoding';
  if (/\b(blood relation|son of|daughter of|wife of|husband of|mother of|father of|sister of|brother of)\b/.test(text)) return 'Blood Relations';
  if (/\b(direction|towards (north|south|east|west)|km towards)\b/.test(text)) return 'Direction Sense';
  if (/\b(statement(s)? and conclusion|syllogism)\b/.test(text)) return 'Syllogism';
  if (/\b(venes?|venn)\b/.test(text)) return 'Venn Diagrams';
  if (/\b(is related to|analogy)\b/.test(text)) return 'Analogy';
  if (/\b(series|should come in place of|letter-cluster|alphabetical order|number-pairs)\b/.test(text)) return 'Series';
  return 'Reasoning';
}

function classifyQuantTopic(text) {
  if (/\b(simple interest|compound interest|per annum|interest)\b/.test(text)) return 'SI & CI';
  if (/\b(profit|loss|discount|marked price|dealer|sells)\b/.test(text)) return 'Profit & Loss';
  if (/\b(ratio|proportion|proportional|partnership)\b/.test(text)) return 'Ratio & Proportion';
  if (/\b(work|cistern|tap|pipes?|efficiency|fills|empty)\b/.test(text)) return 'Time & Work';
  if (/\b(percent|%)\b/.test(text)) return 'Percentage';
  if (/\b(area|perimeter|volume|hexagon|triangle|quadrilateral|circle|cylinder|sphere|mensuration|square)\b/.test(text)) return 'Mensuration';
  if (/\b(algebra|equation|quadratic|polynomial)\b/.test(text)) return 'Algebra';
  return 'Quantitative Aptitude';
}

/* ------------------------------------------------------------------ */
/* Main                                                                */
/* ------------------------------------------------------------------ */

async function main() {
  const parser = new PDFParse(new Uint8Array(fs.readFileSync(PDF_PATH)));
  await parser.load();
  const numPages = parser.doc.numPages;
  console.log(`Loaded ${PDF_PATH} (${numPages} pages)`);

  // Locate the first page of every shift from its "Test Center Name" header.
  const starts = [];
  for (let p = 1; p <= numPages; p++) {
    const page = await parser.doc.getPage(p);
    const tc = await page.getTextContent();
    const str = tc.items.map((it) => it.str).join(' ').replace(/\s+/g, ' ');
    if (/Test Center Name/i.test(str)) {
      const date = (str.match(/Test Date\s*(.*?)\s*Test Time/i) || [])[1] || '';
      const time = (str.match(/Test Time\s*(.*?)\s*Subject/i) || [])[1] || '';
      starts.push({ page: p, examDate: date.trim(), shiftTiming: time.trim() });
    }
  }
  console.log(`Detected ${starts.length} shifts`);

  const shifts = [];
  const questions = [];
  let totalNeedsReview = 0;

  for (let s = 0; s < starts.length; s++) {
    const shiftNumber = s + 1;
    const from = starts[s].page;
    const to = s + 1 < starts.length ? starts[s + 1].page - 1 : numPages;

    let chars = [];
    for (let p = from; p <= to; p++) chars = chars.concat(await pageChars(parser, p));
    chars = stripBoilerplate(chars);
    const text = chars.map((c) => c.ch).join('');
    const markers = findMarkers(text);

    const shiftQuestions = [];
    for (let i = 0; i < markers.length; i++) {
      const mk = markers[i];
      const blockEnd = i + 1 < markers.length ? markers[i + 1].start : markers.length ? text.length : 0;
      const block = chars.slice(mk.end, blockEnd);
      const parsed = parseQuestion(block, 'A');
      const classification = classifySubject(parsed.questionText, parsed.options);
      const correctIndex = LETTERS.indexOf(parsed.correctLetter);

      const isComplete =
        parsed.questionText.length > 12 &&
        parsed.options.length === 4 &&
        parsed.options.every((o) => o.length > 0) &&
        parsed.hasGreen;
      if (!isComplete) totalNeedsReview++;

      const q = {
        id: `rrb-ntpc-grad-2025-s${shiftNumber}-q${mk.num}`,
        examLevel: 'Graduate',
        examCode: 'CEN 06/2025',
        shiftNumber,
        examName: 'RRB NTPC Graduate 2025 (CBT-1)',
        examYear: '2025',
        examDate: starts[s].examDate,
        shiftTiming: starts[s].shiftTiming,
        questionNumber: mk.num,
        subject: classification.subject,
        subjectId: classification.subjectId,
        subtopic: classification.subtopic,
        question: { en: parsed.questionText, te: '' },
        options: { en: [parsed.options[0] || '', parsed.options[1] || '', parsed.options[2] || '', parsed.options[3] || ''], te: ['', '', '', ''] },
        correctAnswer: correctIndex >= 0 ? correctIndex : 0,
        correctLetter: parsed.correctLetter,
        explanation: {
          en: `Official Answer: Option (${parsed.correctLetter}). From RRB NTPC Graduate 2025 (CEN 06/2025) CBT-1 Shift ${shiftNumber}, held ${starts[s].examDate}.`,
          te: ''
        },
        status: isComplete ? 'Published' : 'Needs Review',
        source: 'RRB NTPC Graduate 2025 Official Answer Key (CEN 06/2025)',
        paperUrl: '/assets/aistudio/RRB-NTPC-Graduate-2025-CBT1-EN-Official-Answer-Key.pdf',
        paperFileName: 'RRB-NTPC-Graduate-2025-CBT1-EN-Official-Answer-Key.pdf',
        createdAt: new Date().toISOString()
      };

      shiftQuestions.push(q);
      questions.push(q);
    }

    const subjectCounts = { 'Quantitative Aptitude': 0, 'General Knowledge': 0, 'General Science': 0, 'Reasoning': 0 };
    for (const q of shiftQuestions) if (subjectCounts[q.subject] !== undefined) subjectCounts[q.subject]++;

    shifts.push({
      id: `rrb-ntpc-grad-2025-shift-${shiftNumber}`,
      code: `RRB-NTPC-GRAD-S${shiftNumber}`,
      examLevel: 'Graduate',
      examLevelLabel: 'Graduate',
      shiftNumber,
      title: `RRB NTPC Graduate 2025 – Shift ${shiftNumber}`,
      subtitle: `${starts[s].examDate} · ${starts[s].shiftTiming}`,
      examName: 'RRB NTPC Graduate 2025 (CEN 06/2025)',
      examYear: '2025',
      examDate: starts[s].examDate,
      shiftTiming: starts[s].shiftTiming,
      durationMinutes: 90,
      totalMarks: 100,
      negativeMarking: 0.33,
      totalQuestions: shiftQuestions.length,
      subjectCounts,
      questionsCount: shiftQuestions.length,
      status: 'Published'
    });
    console.log(`Shift ${shiftNumber}: parsed ${shiftQuestions.length} questions (pages ${from}-${to})`);
  }

  const payload = {
    metadata: {
      generatedAt: new Date().toISOString(),
      examName: 'RRB NTPC Graduate 2025 (CEN 06/2025)',
      examLevel: 'Graduate',
      totalShifts: shifts.length,
      totalQuestions: questions.length,
      totalNeedsReview,
      subjects: ['General Knowledge', 'Reasoning', 'Quantitative Aptitude', 'General Science'],
      source: 'RRB-NTPC-Graduate-2025-CBT1-EN-Official-Answer-Key.pdf'
    },
    shifts,
    questions
  };

  fs.mkdirSync('public/data', { recursive: true });
  fs.writeFileSync(OUT_PATH, JSON.stringify(payload, null, 2));
  console.log(`\nSaved ${questions.length} questions across ${shifts.length} shifts -> ${OUT_PATH}`);
  console.log(`Needs Review: ${totalNeedsReview}`);

  const bySubject = {};
  for (const q of questions) bySubject[q.subject] = (bySubject[q.subject] || 0) + 1;
  console.log('By subject:', bySubject);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
